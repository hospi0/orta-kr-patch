def patch(ko, rel, table, label):
    key = None
    for k in ko:
        if k.replace('/', '\\') == rel.replace('/', '\\'):
            key = k
            break
    if key is None:
        print('★%s 를 ko.json 에서 못 찾음' % label)
        return 0
    d = ko[key]
    tot = 0
    for idx, new in table.items():
        old = d.get(str(idx))
        if old is None:
            print('  ★idx%d 없음' % idx)
            continue
        if old.count('\n') != new.count('\n'):
            print('  idx%-4d 줄 수 %d -> %d (의도된 복원)'
                  % (idx, old.count('\n') + 1, new.count('\n') + 1))
        g = K.nbytes(old) - K.nbytes(new)
        tot += g
        print('  idx%-4d %4dB -> %4dB (%+dB)' % (idx, K.nbytes(old), K.nbytes(new), -g))
        d[str(idx)] = new
    print('%s 합계 %+dB' % (label, -tot))
    return tot


def main():
    apply = '--apply' in sys.argv
    ko = json.load(open(KO, encoding='utf-8'))
    print('world 축약')
    patch(ko, WORLD, WORLD_NEW, 'world')
    print('creature 개행 복원')
    patch(ko, CREA, CREA_NEW, 'creature')
    if apply:
        shutil.copy2(KO, KO + '.bak4')
        with open(KO, 'w', encoding='utf-8', newline='') as f:
            json.dump(ko, f, ensure_ascii=False, indent=1)
        print('\n적용 -> %s' % KO)
    else:
        print('\n※ 보고만. 반영하려면 --apply')


if __name__ == '__main__':
    main()
