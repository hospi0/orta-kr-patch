def main():
    apply = '--apply' in sys.argv
    ko = json.load(open(KO, encoding='utf-8'))
    d = ko[REL]
    tot = 0
    for idx, new in NEW.items():
        old = d[str(idx)]
        if old.count('\n') != new.count('\n'):
            print('★idx%d 줄 수가 다르다 %d -> %d — 건너뜀'
                  % (idx, old.count('\n') + 1, new.count('\n') + 1))
            continue
        g = K.nbytes(old) - K.nbytes(new)
        tot += g
        print('idx%-4d %4dB -> %4dB  (-%dB)' % (idx, K.nbytes(old), K.nbytes(new), g))
        if apply:
            d[str(idx)] = new
    print('\n합계 %d B 절약' % tot)
    if apply:
        shutil.copy2(KO, KO + '.bak2')
        with open(KO, 'w', encoding='utf-8', newline='') as f:
            json.dump(ko, f, ensure_ascii=False, indent=1)
        print('적용 -> %s' % KO)
    else:
        print('※ 보고만. 반영하려면 --apply')


if __name__ == '__main__':
    main()
